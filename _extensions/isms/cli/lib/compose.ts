import { parse as parseYaml, stringify as stringifyYaml } from "stdlib/yaml";
import { join } from "stdlib/path"
import { DocumentSpec, Project } from "./project.ts"
import {
  emit,
  isAncestor,
  OverrideOp,
  ParsedDoc,
  ParseError,
  parseDocument,
  parseOverrides,
} from "./blocks.ts";
import {
  collectDeviations,
  type Deviation,
  DEVIATIONS_PATH,
  governanceWarnings,
  renderRegister,
} from "./deviations.ts";

export const COMPOSED_DIR = "docs";
/**
 * Institution override sources. Underscore-prefixed so Quarto treats the directory as project
 * material rather than as pages to render — the overrides are spliced into `docs/` instead.
 */
export const OVERRIDES_DIR = "_overrides";

export interface ComposedDoc {
  ismsId: string;
  title: string;
  path: string;
  /** `_overrides/<ID>.qmd`, when the institution has one — the register cites it by line. */
  overrideSource?: string;
  /** Every override applied to this document, in baseline block order. */
  deviations: Deviation[];
}

export interface ComposeResult {
  files: Map<string, string>;
  docs: ComposedDoc[];
  /** Governance gaps worth naming. Not errors: composition still succeeded. */
  warnings: string[];
}

export async function compose(project: Project): Promise<ComposeResult> {
  const { root, baseline } = project;
  const baselineVersion = baseline.manifest.baseline_version;
  const files = new Map<string, string>();
  const docs: ComposedDoc[] = [];
  const warnings: string[] = [];

  // Hoisted: it does not vary per document, and the deviations register carries the identical
  // line, so both kinds of generated artefact are marked the same way.
  const banner =
    `<!-- GENERATED by \`isms compose\` from ISMS baseline ${baselineVersion}. DO NOT EDIT BY HAND. -->`;

  for (const spec of baseline.manifest.documents) {
    const baselinePath = join(baseline.dir, spec.file);
    const src = Deno.readTextFileSync(baselinePath);
    const parsed: ParsedDoc = parseDocument(baselinePath, src);

    const { path: overrideSource, ops } = loadOverrides(root, spec, parsed);

    const baseMeta = (parseYaml(parsed.frontMatter || "{}") ?? {}) as Record<string, unknown>;

    const body = emit(parsed.root, ops, true);
    const composed = `---\n${stringifyYaml(baseMeta, { sortKeys: true, lineWidth: 100 })}---\n\n${banner}\n${body}\n`;
    const relPath = join(COMPOSED_DIR, `${spec.id}-${slug(spec.title)}.qmd`);
    files.set(relPath, tidy(composed));

    // Anchors are resolved against `body`, before tidy() collapses blank lines and renumbers
    // them. Safe, because only positions relative to each other within this one string matter.
    const deviations = collectDeviations(body, ops, parsed.blocks);
    if (overrideSource) warnings.push(...governanceWarnings(overrideSource, deviations));

    docs.push({
      ismsId: spec.id,
      title: (baseMeta.title as string) ?? spec.title,
      path: relPath,
      overrideSource,
      deviations,
    })
  }

  files.set(DEVIATIONS_PATH, tidy(renderRegister(banner, baselineVersion, docs)));
  return { files, docs, warnings };
}

/**
 * Read the institution's override file for one baseline document, if it has one.
 *
 * Overrides live in `<root>/_overrides/<ISMS-ID>.qmd` — one file per document, keyed on the
 * ID rather than the title, so retitling a baseline document does not orphan its overrides.
 * Absence is the normal case: a document with no override file is adopted verbatim.
 */
function loadOverrides(
  root: string,
  spec: DocumentSpec,
  parsed: ParsedDoc,
): { path?: string; ops: Map<string, OverrideOp> } {
  // The relative path is what the deviations register cites; an absolute one would leak the
  // composing machine's filesystem into a rendered audit page. Errors keep the absolute path,
  // where a full path is what you want in a terminal.
  const rel = join(OVERRIDES_DIR, `${spec.id}.qmd`);
  const path = join(root, rel);
  let src: string;
  try {
    src = Deno.readTextFileSync(path);
  } catch (err) {
    if (err instanceof Deno.errors.NotFound) return { ops: new Map() };
    throw err;
  }

  const { document, ops } = parseOverrides(path, src);
  if (document !== undefined && document !== spec.id) {
    throw new ParseError(path, 1, `front matter says document: ${document}, but this file overrides ${spec.id}`);
  }

  for (const op of ops.values()) {
    // A typo in a block ID would otherwise be a silent no-op, which is the worst possible
    // outcome for something an approver has signed off on.
    if (!parsed.blocks.has(op.id)) {
      throw new ParseError(
        path,
        op.line,
        `${spec.id} has no block "${op.id}". Overridable blocks: ${[...parsed.blocks.keys()].join(", ")}`,
      );
    }
    // Replacing or deleting a block discards its children, so an override on a descendant
    // of one would never reach the output. Fail loudly rather than drop it.
    if (op.mode !== "replace" && op.mode !== "delete") continue;
    for (const inner of ops.values()) {
      if (isAncestor(op.id, inner.id)) {
        throw new ParseError(
          path,
          inner.line,
          `override "${inner.id}" sits inside "${op.id}", which is overridden with ` +
          `mode=${op.mode} (line ${op.line}) and would discard it`,
        );
      }
    }
  }
  return { path: rel, ops };
}

function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}


/** Collapse the blank-line noise that splicing inevitably produces. */
function tidy(s: string): string {
  return s.replace(/\n{3,}/g, "\n\n").replace(/\s+$/, "") + "\n";
}
